records = [
    ("samsung", 100, 2),
    ("poco", 50, 5),
    ("iphone", 120, 1),
    ("samsung", 80, 1),
]


def total_by_id(records: list[tuple[str, float, int]]) -> list[tuple[str, float]]:
    """Посчитать общую стоимость для каждого идентификатора и отсортировать ее."""

    # Словарь здесь потому, что один идентификатор может встретиться
    # в нескольких записях. Идентификатор будет ключом, а накопленная сумма -
    # значением этого ключа.
    totals = {}

    for identifier, price, quantity in records:
        # При первом появлении идентификатора get() вернет ноль.
        # При следующих появлениях get() вернет уже накопленную сумму, и к
        # ней прибавится стоимость текущей записи.
        totals[identifier] = totals.get(identifier, 0) + price * quantity

    # items() дает пары вида (идентификатор, сумма). Параметр key говорит
    # sorted(), что сравнивать нужно второй элемент пары, а reverse=True
    # помещает самую большую сумму в начало результата.
    return sorted(totals.items(), key=lambda item: item[1], reverse=True)


# Этот небольшой пример позволяет вручную проверить функцию. Samsung
# встречается дважды, поэтому его сумма должна быть 100 * 2 + 80 * 1 = 280.
print(total_by_id(records))